'use strict';

// Discovers model-authored dynamic Cordis plugins from durable DSH session
// logs and promotes reviewed Host-only definitions into local profile bundles.
// Dynamic definitions are process-local by design, but their tool calls are
// retained in session.jsonl.zstd; scanning the logs is therefore the only
// restart-safe inventory available to a wrapper.

const { createHash } = require('node:crypto');
const { spawn } = require('node:child_process');
const {
  existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync,
  symlinkSync, writeFileSync,
} = require('node:fs');
const { dirname, join, relative } = require('node:path');

function readJson(file, fallback) { try { return JSON.parse(readFileSync(file, 'utf8')); } catch { return fallback; } }
function writeJsonAtomic(file, value) {
  mkdirSync(dirname(file), { recursive: true });
  const temporary = `${file}.tmp-${process.pid}`;
  writeFileSync(temporary, `${JSON.stringify(value, null, 2)}\n`, { mode: 0o600 });
  renameSync(temporary, file);
}
function sha(value) { return createHash('sha256').update(value).digest('hex'); }
function slug(value) { return String(value || 'plugin').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 36) || 'plugin'; }

function sessionLogs(root) {
  const found = [];
  const visit = (directory) => {
    let entries = [];
    try { entries = readdirSync(directory, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.name === 'session.jsonl.zstd' || entry.name === 'session.jsonl') found.push(path);
    }
  };
  visit(root);
  return found;
}

function readLogLines(file, onLine) {
  return new Promise((resolve, reject) => {
    const child = file.endsWith('.zstd') ? spawn('zstdcat', [file]) : spawn('cat', [file]);
    let buffer = '';
    child.stdout.on('data', (chunk) => {
      buffer += chunk;
      let newline;
      while ((newline = buffer.indexOf('\n')) >= 0) {
        const line = buffer.slice(0, newline); buffer = buffer.slice(newline + 1);
        if (line) onLine(line);
      }
    });
    child.once('error', reject);
    child.once('exit', (code) => {
      if (buffer) onLine(buffer);
      if (code === 0) resolve(); else reject(new Error(`could not read session log ${file}`));
    });
  });
}

function toolCalls(event) {
  const output = [];
  const content = event?.data?.message?.content;
  if (Array.isArray(content)) {
    for (const block of content) if (block?.type === 'tool-call' && typeof block.name === 'string') output.push({ id: block.id, name: block.name, arguments: block.arguments });
  }
  const call = event?.data?.call;
  if (call?.name) output.push({ id: call.id, name: call.name, arguments: call.arguments ?? call.args });
  return output;
}

function parseArguments(value) {
  if (value && typeof value === 'object') return value;
  try { return JSON.parse(String(value)); } catch { return null; }
}

async function scanDynamicCordisPlugins({ sessionsDir, limit = 500 } = {}) {
  const plugins = new Map();
  const logs = sessionLogs(sessionsDir).slice(-limit);
  for (const file of logs) {
    await readLogLines(file, (line) => {
      let event; try { event = JSON.parse(line); } catch { return; }
      for (const call of toolCalls(event)) {
        if (!['cordis_define', 'cordis_run'].includes(call.name)) continue;
        const args = parseArguments(call.arguments); if (!args) continue;
        if (call.name === 'cordis_define' && args.code && (typeof args.code.host === 'string' || typeof args.code.client === 'string')) {
          const host = typeof args.code.host === 'string' ? args.code.host : '';
          const client = typeof args.code.client === 'string' ? args.code.client : '';
          const key = sha(`${file}\0${host}\0${client}`).slice(0, 20);
          const pluginId = args.plugin?.pluginId || args.plugin?.idPrefix || null;
          plugins.set(key, {
            id: key, pluginId, name: String(args.name || pluginId || 'Dynamic Cordis plugin'), purpose: String(args.purpose || ''),
            host, client, hasClient: Boolean(client), wasRun: false, sessionLog: file, time: event.time || event.time0 || null,
          });
        }
        if (call.name === 'cordis_run') {
          const id = args.pluginId;
          for (const item of plugins.values()) if (id && item.pluginId === id) item.wasRun = true;
        }
      }
    });
  }
  return [...plugins.values()].sort((a, b) => Number(b.wasRun) - Number(a.wasRun) || Number(b.time || 0) - Number(a.time || 0));
}

function generatedIndex(source, displayName) {
  return `// Generated by DSH Desktop from a user-approved dynamic Cordis definition.\n// Original source is preserved verbatim below for review and rollback.\nimport { defineTool } from '@deepseek-ai/dsh-tools';\n\nconst source = ${JSON.stringify(source)};\nconst harness = Object.freeze({\n  defineTool,\n  registerTool(ctx, tool) {\n    if (!ctx?.tools?.register) throw new Error('DSH tool registry is unavailable');\n    return ctx.tools.register(tool);\n  },\n});\n\nexport const name = ${JSON.stringify(displayName)};\nexport function apply(ctx) {\n  const factory = new Function('harness', '\\"use strict\\";\\n' + source);\n  const plugin = factory(harness);\n  if (!plugin || typeof plugin.apply !== 'function') throw new Error('Promoted Cordis source must return a Plugin object with apply(ctx)');\n  return plugin.apply(ctx);\n}\n`;
}

async function promoteDynamicPlugin({ profileDir, sessionsDir, id }) {
  const definitions = await scanDynamicCordisPlugins({ sessionsDir });
  const definition = definitions.find((item) => item.id === id);
  if (!definition) throw new Error('dynamic plugin definition is no longer available in session history');
  if (!definition.host) throw new Error('client-only dynamic plugins cannot be promoted yet');
  if (definition.client) throw new Error('host + client dynamic plugins need a reviewed browser bundle and cannot be auto-promoted yet');
  const packageName = `dsh-local-cordis-${slug(definition.name)}-${definition.id.slice(0, 8)}`;
  const localRoot = join(profileDir, '.dsh-desktop-local-plugins');
  const packageDir = join(localRoot, packageName);
  const nodeModule = join(profileDir, 'node_modules', packageName);
  const manifestFile = join(profileDir, 'package.json');
  const manifest = readJson(manifestFile, null);
  if (!manifest || typeof manifest !== 'object') throw new Error(`invalid profile manifest: ${manifestFile}`);
  manifest.dependencies ??= {}; manifest.dsh ??= {}; manifest.dsh.profile ??= {}; manifest.dsh.profile.bundles ??= [];
  const existing = manifest.dsh.profile.bundles.includes(packageName);
  if (!existsSync(packageDir)) {
    mkdirSync(packageDir, { recursive: true, mode: 0o700 });
    writeJsonAtomic(join(packageDir, 'package.json'), {
      name: packageName, version: '0.0.1', private: true, type: 'module',
      dsh: { bundle: { patch: './cordis.patch.yml' } },
      peerDependencies: { '@deepseek-ai/dsh-tools': '^0.1.1-rc.2' },
    });
    writeFileSync(join(packageDir, 'cordis.patch.yml'), `- insert:\n    - id: ${packageName}\n      name: ${packageName}\n`, { mode: 0o600 });
    writeFileSync(join(packageDir, 'index.js'), generatedIndex(definition.host, definition.name), { mode: 0o600 });
    writeJsonAtomic(join(packageDir, 'dsh-desktop-source.json'), { ...definition, promotedAt: new Date().toISOString() });
  }
  if (!existsSync(nodeModule)) {
    mkdirSync(dirname(nodeModule), { recursive: true });
    symlinkSync(relative(dirname(nodeModule), packageDir), nodeModule, 'dir');
  }
  manifest.dependencies[packageName] = `file:.dsh-desktop-local-plugins/${packageName}`;
  if (!existing) manifest.dsh.profile.bundles.push(packageName);
  writeJsonAtomic(manifestFile, manifest);
  return { packageName, packageDir, sourceId: definition.id, alreadyInstalled: existing };
}

module.exports = { promoteDynamicPlugin, scanDynamicCordisPlugins };
